export function uiLanguage(): "zh" | "en" {
  // getLanguage was added in 1.8.7. Older supported hosts expose their language through Moment.
  const language = requireApiVersion("1.8.7") ? getLanguage() : moment.locale();
  return /^zh(?:[-_]|$)/i.test(language) ? "zh" : "en";
}

export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = (uiLanguage() === "zh" ? zh : en)[key];
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}

export function formatDate(date: Date, options: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(uiLanguage() === "zh" ? "zh-CN" : "en-US", options).format(date);
}

export function weekdayLabels(): string[] {
  // Keep the existing Monday-first grid independently of the language.
  return Array.from({ length: 7 }, (_, index) => formatDate(new Date(2024, 0, 1 + index), { weekday: "short" }));
}

export function monthHeading(date: Date): string {
  return formatDate(date, { year: "numeric", month: "long" });
}

export function weekHeading(start: Date, end: Date): string {
  const options: Intl.DateTimeFormatOptions = { month: "short", day: "numeric" };
  return `${formatDate(start, options)} – ${formatDate(end, options)}`;
}

export function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}
