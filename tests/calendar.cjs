const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {module:{exports:{}},require:()=>({requireApiVersion:()=>true,getLanguage:()=> 'zh',Plugin:class{},ItemView:class{},Modal:class{},PluginSettingTab:class{}})};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','main.js'),'utf8') + '\nmodule.exports.calendar={dateKey,parseDate,validDate,addDays,addMonths,startOfWeek,weekNumber,placeEvents,eventInterval,categoryOf,endDateOf,eventDates,occursOn,overlapsDates,dayTimeRange,durationInDates,shiftedDates,validateEventRange};',context);
const c = context.module.exports.calendar;
assert.equal(c.validDate('2026-02-29'),false);
assert.equal(c.validDate('2028-02-29'),true);
assert.equal(c.dateKey(c.addMonths(c.parseDate('2026-01-31'),1)),'2026-02-28');
assert.equal(c.dateKey(c.addMonths(c.parseDate('2026-03-31'),-1)),'2026-02-28');
assert.equal(c.dateKey(c.addDays(c.parseDate('2026-12-31'),1)),'2027-01-01');
assert.equal(c.dateKey(c.startOfWeek(c.parseDate('2026-11-01'))),'2026-10-26');
assert.equal(c.weekNumber(c.parseDate('2027-01-01')),53);
assert.equal(c.weekNumber(c.parseDate('2027-01-04')),1);
assert.equal(c.categoryOf({}), 'work', 'Legacy appointments receive the default calendar');
const event=(id,startTime,endTime)=>({id,startTime,endTime});
const placed=c.placeEvents([event('a','09:00','10:00'),event('b','09:30','11:00'),event('c','10:00','10:30'),event('d','11:00','12:00')]);
const find=id=>placed.find(item=>item.event.id===id);
assert.equal(find('a').lane,find('c').lane,'An ended appointment frees its lane');
assert.notEqual(find('a').lane,find('b').lane,'Concurrent appointments remain visible');
assert.equal(find('a').lanes,2); assert.equal(find('c').lanes,2);
assert.equal(find('d').lanes,1,'A new non-overlapping group gets the full column');
const short=c.placeEvents([event('x','09:00','09:15'),event('y','09:15','09:30')]);
assert.notEqual(short[0].lane,short[1].lane,'Short visible blocks also remain separate');
assert.equal(c.eventInterval(event('end-only','','10:00')).start,540,'Legacy end-only appointments can be placed');
assert.equal(c.eventInterval(event('no-end','23:30','')).end,1440,'Inferred duration remains within the day');
const overnight={...event('night','22:00','02:00'),date:'2026-10-31',endDate:'2026-11-01'};
assert.deepEqual(Array.from(c.eventDates(overnight)),['2026-10-31','2026-11-01']);
assert.equal(c.eventInterval(overnight,'2026-10-31').end,1440);
assert.equal(c.eventInterval(overnight,'2026-11-01').start,0);
assert.equal(c.eventInterval(overnight,'2026-11-01').end,120);
assert.equal(c.durationInDates(overnight,'2026-10-01','2026-10-31'),2);
assert.equal(c.durationInDates(overnight,'2026-11-01','2026-11-30'),2);
assert.equal(c.overlapsDates(overnight,'2026-11-01','2026-11-30'),true);
assert.equal(c.dayTimeRange(overnight,'2026-10-31'),'22:00 – 24:00 · 跨天');
assert.equal(c.shiftedDates(overnight,'2026-11-01','2027-01-01').date,'2026-12-31');
assert.equal(c.shiftedDates(overnight,'2026-11-01','2027-01-01').endDate,'2027-01-01');
const allDay={...overnight,startTime:'',endTime:'',endDate:'2026-11-02'};
assert.equal(c.eventDates(allDay).length,3,'All-day end date is inclusive');
const midnight={...overnight,endTime:'00:00'};
assert.deepEqual(Array.from(c.eventDates(midnight)),['2026-10-31'],'An event ending at midnight does not occupy the next day');
assert.equal(c.occursOn(midnight,'2026-11-01'),false);
assert.equal(c.shiftedDates(midnight,'2026-10-31','2026-12-31').endDate,'2027-01-01');
assert.equal(c.eventDates({...allDay,date:'2028-02-28',endDate:'2028-03-01'}).length,3,'Leap-day ranges');
assert.throws(()=>c.validateEventRange({...overnight,endDate:'2026-10-30'}),/结束日期/);
assert.throws(()=>c.shiftedDates(overnight,'2026-10-29','2026-11-02'),/移动的日期/);
c.validateEventRange(overnight);
console.log('PASS: leap dates, month navigation, cross-year/ISO weeks, legacy categories/times, timeline overlap groups, lane reuse and short appointments.');
console.log('PASS: overnight segments, midnight exclusion, inclusive all-day ranges, month boundaries, leap day, range validation and shifting from a continuation day.');
